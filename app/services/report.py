
import csv
from pathlib import Path
from dataclasses import dataclass, field
from typing import Any


@dataclass
class CleaningReport:
    input_file: str
    output_file: str = ""
    sheets_processed: int = 0
    rows_processed: int = 0
    blank_rows_removed: int = 0
    duplicate_rows_removed: int = 0
    null_values_replaced: int = 0
    values_trimmed: int = 0
    invalid_values: list[dict[str, Any]] = field(default_factory=list)
    changes: list[dict[str, Any]] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)

    # AutoGen analysis
    ai_analysis: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "input_file": self.input_file,
            "output_file": self.output_file,
            "sheets_processed": self.sheets_processed,
            "rows_processed": self.rows_processed,
            "blank_rows_removed": self.blank_rows_removed,
            "duplicate_rows_removed": self.duplicate_rows_removed,
            "null_values_replaced": self.null_values_replaced,
            "values_trimmed": self.values_trimmed,
            "invalid_values": self.invalid_values,
            "changes": self.changes,
            "errors": self.errors,
        }


def export_report_csv(report: CleaningReport) -> str:
    """Export the Excel cleaning report to CSV."""

    output_path = Path(report.output_file)

    if not report.output_file:
        raise ValueError("Output file path is required")

    csv_path = output_path.with_name(
        output_path.stem.removesuffix("_cleaned")
        + "_cleaning_report.csv"
    )

    with open(
        csv_path,
        "w",
        newline="",
        encoding="utf-8-sig"
    ) as file:

        writer = csv.writer(file)

        # CSV headers
        writer.writerow([
            "Record Type",
            "Sheet",
            "Row",
            "Column",
            "Original Value",
            "New Value",
            "Reason",
        ])

        # 1. Cleaning statistics
        statistics = {
            "Sheets processed": report.sheets_processed,
            "Rows processed": report.rows_processed,
            "Blank rows removed": report.blank_rows_removed,
            "Duplicates removed": report.duplicate_rows_removed,
            "Null values replaced": report.null_values_replaced,
            "Values trimmed": report.values_trimmed,
            "Suspicious values": len(report.invalid_values),
        }

        for name, value in statistics.items():
            writer.writerow([
                "Summary", "", "", name, "", value, ""
            ])

        # 2. Individual cleaning changes
        for change in report.changes:
            writer.writerow([
                "Change",
                change.get("sheet", ""),
                change.get("row", ""),
                change.get("column", ""),
                change.get("original_value", ""),
                change.get("new_value", ""),
                change.get("reason", ""),
            ])

        # 3. Invalid or suspicious values
        for issue in report.invalid_values:
            writer.writerow([
                "Suspicious Value",
                issue.get("sheet", ""),
                issue.get("row", ""),
                issue.get("column", ""),
                issue.get("value", ""),
                "",
                issue.get("reason", ""),
            ])

        # 4. AutoGen AI analysis
        if report.ai_analysis:
            writer.writerow([
                "AI Analysis",
                "",
                "",
                "Data Quality Analysis",
                "",
                report.ai_analysis,
                "Generated by AutoGen",
            ])

        # 5. Errors
        for error in report.errors:
            writer.writerow([
                "Error", "", "", "", "", "", error
            ])

    return str(csv_path)
